//! Compiles `proto/` with protox (pure Rust: no system `protoc`, so the client
//! and bot repos build this crate as a git dependency on any host) and writes
//! the descriptor set the wire-surface test reads.

use std::path::PathBuf;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("cargo:rerun-if-changed=proto");
    println!("cargo:rerun-if-changed=redacted_debug.txt");
    let files = protox::compile(["yapsta/v1/yapsta.proto"], ["proto"])?;
    #[allow(
        clippy::disallowed_methods,
        reason = "a build script reads OUT_DIR from env"
    )]
    let out = PathBuf::from(std::env::var("OUT_DIR")?);
    std::fs::write(
        out.join("yapsta_v1.bin"),
        prost::Message::encode_to_vec(&files),
    )?;
    // The schema table `frame::decoded_bound` walks (src/bound.rs).
    std::fs::write(out.join("bound_schema.rs"), bound_schema(&files)?)?;
    // Messages with a secret or user text get hand-written, redacting Debug
    // impls (src/debug.rs), so a stray `{:?}` cannot log them. The list is
    // shared with tests/wire_surface.rs, which classifies every text field.
    let redacted = include_str!("redacted_debug.txt")
        .lines()
        .filter(|l| !l.is_empty())
        .map(|l| format!(".{l}"));
    prost_build::Config::new()
        .skip_debug(redacted)
        // An image (§ 6.5) is served to many sessions from one buffer:
        // cloning a reply shares it. The Rust type only; the wire is the same.
        .bytes([".yapsta.v1.BlobData.data"])
        .compile_fds(files)?;
    Ok(())
}

/// Repeated fields one message may have: the walker counts them in a fixed
/// array on the stack (src/bound.rs, `MAX_REPEATED`).
const MAX_REPEATED: usize = 16;

/// Rust source for the table `frame::decoded_bound` walks: for each message,
/// its Rust size and, sorted by tag, each field's kind. Every message is a
/// top-level `crate::v1::Name` (a test in src/bound.rs holds that the table
/// covers the schema).
fn bound_schema(
    files: &prost_types::FileDescriptorSet,
) -> Result<String, Box<dyn std::error::Error>> {
    let messages: Vec<_> = files.file.iter().flat_map(|f| &f.message_type).collect();
    let index = |type_name: &str| {
        let name = type_name.trim_start_matches(".yapsta.v1.");
        messages.iter().position(|m| m.name() == name)
    };
    let mut src = String::from(
        "// Generated by build.rs from proto/yapsta/v1/yapsta.proto.\n\
         pub(crate) static MESSAGES: &[Message] = &[\n",
    );
    let mut envelope = None;
    for (i, message) in messages.iter().enumerate() {
        if !message.nested_type.is_empty() {
            return Err(format!(
                "{}: nested messages need a path in bound_schema",
                message.name()
            )
            .into());
        }
        if message.name() == "Envelope" {
            envelope = Some(i);
        }
        let mut fields: Vec<_> = message.field.iter().collect();
        fields.sort_by_key(|f| f.number());
        let mut slot = 0;
        src.push_str(&format!(
            "    Message {{ name: {:?}, size: ::core::mem::size_of::<crate::v1::{}>(), fields: &[\n",
            message.name(),
            message.name()
        ));
        for field in fields {
            // FieldDescriptorProto.Type and .Label numbers (descriptor.proto).
            let kind = match field.r#type.unwrap_or(0) {
                11 => {
                    let target = index(field.type_name())
                        .ok_or_else(|| format!("{}: unknown type", field.type_name()))?;
                    format!("Kind::Message({target})")
                }
                9 | 12 => "Kind::Bytes".to_owned(),
                // int64, uint64, int32, bool, uint32, enum, sint32, sint64
                3 | 4 | 5 | 13 | 14 | 17 | 18 => {
                    let size = if matches!(field.r#type, Some(3 | 4 | 18)) {
                        8
                    } else {
                        4
                    };
                    format!("Kind::Varint({size})")
                }
                8 => "Kind::Varint(1)".to_owned(),
                // double, fixed64, sfixed64
                1 | 6 | 16 => "Kind::Fixed(8)".to_owned(),
                // float, fixed32, sfixed32
                2 | 7 | 15 => "Kind::Fixed(4)".to_owned(),
                other => {
                    return Err(format!("{}.{}: type {other}", message.name(), field.name()).into());
                }
            };
            let repeated = field.label.unwrap_or(0) == 3;
            let slot_src = if repeated {
                slot += 1;
                format!("Some({})", slot - 1)
            } else {
                "None".to_owned()
            };
            src.push_str(&format!(
                "        Field {{ tag: {}, kind: {kind}, slot: {slot_src} }},\n",
                field.number()
            ));
        }
        if slot > MAX_REPEATED {
            return Err(format!("{}: over {MAX_REPEATED} repeated fields", message.name()).into());
        }
        src.push_str("    ] },\n");
    }
    let envelope = envelope.ok_or("no Envelope")?;
    src.push_str(&format!(
        "];\npub(crate) const ENVELOPE: usize = {envelope};\npub(crate) const MAX_REPEATED: usize = {MAX_REPEATED};\n"
    ));
    Ok(src)
}
